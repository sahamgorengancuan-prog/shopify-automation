def materialise(
    target_dir: Path | str,
    *,
    port: int = 7860,
    image: str = "archivist:latest",
    user: str = "ubuntu",
    workdir: str = "/opt/archivist",
    windows_workdir: str = r"C:\\archivist",
    gradio_version: str = "",
) -> list[str]:
    """Write every deployment artefact and return the paths written."""
    if not gradio_version:
        try:  # the Space needs the sdk_version it will actually run
            import gradio  # type: ignore

            gradio_version = str(gradio.__version__)
        except Exception:
            gradio_version = "5.0.0"
    target = Path(target_dir)
    target.mkdir(parents=True, exist_ok=True)
    files: dict[str, str] = {
        "Dockerfile": DOCKERFILE.format(port=port),
        "docker-compose.yml": COMPOSE.format(port=port, image=image),
        "archivist.service": SYSTEMD.format(user=user, workdir=workdir, port=port),
        "windows-task.xml": WINDOWS_TASK.format(workdir=windows_workdir, port=port),
        "space_app.py": HF_SPACE_APP,
        "README.md": HF_SPACE_README.format(gradio_version=gradio_version),
        "NOTES.md": NOTES.format(port=port),
    }
    written: list[str] = []
    for name, content in files.items():
        path = target / name
        path.write_text(content, encoding="utf-8")
        written.append(str(path))
    return written


def summary(port: int, target: Path | str) -> dict[str, Any]:
    return {
        "target": str(target),
        "docker": f"docker compose -f {Path(target) / 'docker-compose.yml'} up -d --build",
        "systemd": f"sudo cp {Path(target) / 'archivist.service'} /etc/systemd/system/ && sudo systemctl enable --now archivist",
        "windows": f"schtasks /Create /TN ARCHIVIST /XML {Path(target) / 'windows-task.xml'}",
        "url": f"http://localhost:{port}",
    }
